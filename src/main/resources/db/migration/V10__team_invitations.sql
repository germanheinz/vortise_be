ALTER TABLE usuarios_empresa ADD COLUMN invitante_id BIGINT REFERENCES usuarios_empresa(id);
CREATE INDEX idx_usuarios_invitante_activo ON usuarios_empresa(invitante_id, activo);
CREATE TABLE usuario_empresa_accesos (
    usuario_id BIGINT NOT NULL REFERENCES usuarios_empresa(id),
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    PRIMARY KEY (usuario_id, empresa_id)
);
CREATE INDEX idx_accesos_empresa ON usuario_empresa_accesos(empresa_id);
CREATE TABLE invitaciones_equipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    titular_id BIGINT NOT NULL REFERENCES usuarios_empresa(id),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
    revocado_en TIMESTAMP WITH TIME ZONE,
    consumido_en TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_invitaciones_titular ON invitaciones_equipo(titular_id, id);
CREATE TABLE invitacion_empresas (
    invitacion_id BIGINT NOT NULL REFERENCES invitaciones_equipo(id),
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    PRIMARY KEY (invitacion_id, empresa_id)
);
