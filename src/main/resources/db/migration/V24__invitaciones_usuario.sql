-- Invitaciones para que el administrador incorpore usuarios de su empresa con un rol definido (spec 014).
-- Aditiva. Solo se guarda el hash del token; la persona define su propia contraseña al aceptar.
CREATE TABLE invitaciones_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id) ON DELETE CASCADE,
    creado_por_usuario_id BIGINT NOT NULL REFERENCES usuarios_empresa(id) ON DELETE CASCADE,
    email VARCHAR(254) NOT NULL,
    rol VARCHAR(32) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
    revocado_en TIMESTAMP WITH TIME ZONE,
    consumido_en TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_invitaciones_usuario_empresa ON invitaciones_usuario(empresa_id, id);
CREATE INDEX idx_invitaciones_usuario_email ON invitaciones_usuario(empresa_id, email);
CREATE TABLE invitacion_usuario_obras (
    invitacion_id BIGINT NOT NULL REFERENCES invitaciones_usuario(id) ON DELETE CASCADE,
    proyecto_id BIGINT NOT NULL REFERENCES proyectos(id) ON DELETE CASCADE,
    PRIMARY KEY (invitacion_id, proyecto_id)
);
