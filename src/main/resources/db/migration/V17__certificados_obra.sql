-- Certificates of work per company; quantities are computed from activities and progress loads, never stored.
CREATE TABLE certificados_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    subcontratista_id BIGINT,
    periodicidad VARCHAR(20) NOT NULL,
    numero INTEGER NOT NULL,
    etiqueta VARCHAR(100) NOT NULL,
    fecha_corte DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    creado_por_usuario_id BIGINT,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    cerrado_por_usuario_id BIGINT,
    cerrado_en TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_certificados_obra_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT fk_certificados_obra_subcontratista FOREIGN KEY (subcontratista_id) REFERENCES catalogos_empresa (id)
);
CREATE INDEX ix_certificados_obra_proyecto ON certificados_obra (proyecto_id, subcontratista_id, fecha_corte);

-- An item closed below 100%; it stays closed for the following certificates of the company.
CREATE TABLE certificado_items_completados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificado_id BIGINT NOT NULL,
    rubro_id BIGINT NOT NULL,
    marcado_por_usuario_id BIGINT,
    marcado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_certificado_completados_certificado FOREIGN KEY (certificado_id) REFERENCES certificados_obra (id),
    CONSTRAINT fk_certificado_completados_rubro FOREIGN KEY (rubro_id) REFERENCES rubros_obra (id),
    CONSTRAINT uq_certificado_completados_rubro UNIQUE (rubro_id)
);

