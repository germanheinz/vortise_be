-- PostgreSQL baseline for all current JPA entities. No business rows are inserted here.
-- Java scalar defaults are mirrored where useful; Flyway is the only schema manager in staging.

CREATE TABLE empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    identificacion_fiscal VARCHAR(255),
    limite_usuarios INTEGER NOT NULL DEFAULT 5,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    creado_por_usuario_id BIGINT,
    CONSTRAINT uq_empresas_nombre UNIQUE (nombre),
    CONSTRAINT uq_empresas_identificacion_fiscal UNIQUE (identificacion_fiscal)
);

CREATE TABLE planes_suscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    precio_mensual_centavos BIGINT NOT NULL,
    moneda VARCHAR(255) NOT NULL,
    dias_prueba INTEGER NOT NULL,
    nivel INTEGER NOT NULL,
    beneficios VARCHAR(2000) NOT NULL,
    stripe_price_id VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_planes_suscripcion_codigo UNIQUE (codigo)
);

CREATE TABLE usuarios_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    super_admin BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_usuarios_empresa_email UNIQUE (email),
    CONSTRAINT fk_usuarios_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE proyectos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    presupuesto_usd DOUBLE PRECISION,
    direccion VARCHAR(255),
    numero_proyecto VARCHAR(255),
    fecha_inicio DATE,
    fecha_fin DATE,
    responsables_obra VARCHAR(1000),
    categorias_mano_obra VARCHAR(1000),
    cantidad_sectores INTEGER DEFAULT 1,
    empresa_id BIGINT,
    empresa VARCHAR(255),
    horas_previstas DOUBLE PRECISION,
    horas_reales DOUBLE PRECISION,
    CONSTRAINT fk_proyectos_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE rendimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fase VARCHAR(255),
    etapa VARCHAR(255),
    sistema VARCHAR(255),
    rol VARCHAR(255),
    hh_porm2 DOUBLE PRECISION NOT NULL,
    precio_por_hh DOUBLE PRECISION NOT NULL
);

CREATE TABLE gastos_fijos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto VARCHAR(255) NOT NULL,
    monto DOUBLE PRECISION NOT NULL,
    categoria VARCHAR(255),
    mes INTEGER
);

CREATE TABLE calendarios_laborales_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    horas_lunesaviernes DOUBLE PRECISION DEFAULT 8.0,
    horas_sabado DOUBLE PRECISION DEFAULT 4.0,
    trabaja_domingo BOOLEAN NOT NULL DEFAULT FALSE,
    paga_doble_feriado BOOLEAN NOT NULL DEFAULT FALSE,
    paga_doble_sabado BOOLEAN NOT NULL DEFAULT FALSE,
    paga_doble_no_laborable BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_calendarios_laborales_empresa_empresa UNIQUE (empresa_id),
    CONSTRAINT fk_calendarios_laborales_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE responsables_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    rol VARCHAR(255),
    nombre VARCHAR(255),
    email VARCHAR(255),
    telefono VARCHAR(255),
    CONSTRAINT fk_responsables_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE unidades_metricas_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    codigo VARCHAR(255),
    nombre VARCHAR(255),
    CONSTRAINT fk_unidades_metricas_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE catalogos_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    tipo VARCHAR(255),
    codigo VARCHAR(255),
    nombre VARCHAR(255),
    CONSTRAINT fk_catalogos_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE categorias_mano_obra_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    nombre VARCHAR(255),
    costo_hora DOUBLE PRECISION,
    habilitada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_categorias_mano_obra_empresa_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

CREATE TABLE plantas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    nivel VARCHAR(255) NOT NULL,
    superficie DOUBLE PRECISION,
    sup_cubierta DOUBLE PRECISION,
    sup_descubierta DOUBLE PRECISION,
    sup_calculada DOUBLE PRECISION,
    coef_planta_tipo DOUBLE PRECISION,
    CONSTRAINT fk_plantas_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE rubros_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    n_rubro VARCHAR(255),
    rubro VARCHAR(255),
    nivel VARCHAR(255),
    sub_numero_rubro INTEGER,
    sub_rubro VARCHAR(255),
    cantidad DOUBLE PRECISION,
    unidad VARCHAR(255),
    productividad DOUBLE PRECISION,
    empresa VARCHAR(255),
    tipo_contratista VARCHAR(255) DEFAULT 'PROPIA',
    subcontratista_id BIGINT,
    horas_oficiales_previstas DOUBLE PRECISION,
    horas_ayudantes_previstas DOUBLE PRECISION,
    rendimiento_oficial DOUBLE PRECISION,
    rendimiento_ayudante DOUBLE PRECISION,
    cantidad_personas INTEGER,
    fecha_inicio_planificada DATE,
    fecha_fin_planificada DATE,
    cronograma_manual BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_rubros_obra_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT fk_rubros_obra_subcontratista FOREIGN KEY (subcontratista_id) REFERENCES catalogos_empresa (id)
);

CREATE TABLE registros_horas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    numero_rubro VARCHAR(255),
    rubro VARCHAR(255),
    sub_rubro VARCHAR(255),
    responsable VARCHAR(255),
    etapa VARCHAR(255),
    cantidad_prevista DOUBLE PRECISION,
    cantidad_real DOUBLE PRECISION,
    horas_previstas DOUBLE PRECISION,
    horas_oficiales DOUBLE PRECISION,
    horas_ayudantes DOUBLE PRECISION,
    productividad_presupuesto DOUBLE PRECISION,
    causa_no_cumplimiento VARCHAR(255),
    medida_correctiva VARCHAR(255),
    inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    fin TIMESTAMP WITH TIME ZONE NOT NULL,
    horas DOUBLE PRECISION NOT NULL,
    descripcion VARCHAR(255),
    CONSTRAINT fk_registros_horas_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE presupuesto_lineas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    etapa VARCHAR(255) NOT NULL,
    tipo_superficie VARCHAR(255) NOT NULL,
    funcion VARCHAR(255) NOT NULL,
    sistema VARCHAR(255),
    m2 DOUBLE PRECISION,
    hh_porm2 DOUBLE PRECISION,
    precio_por_hh DOUBLE PRECISION,
    precio_por_hh_usd DOUBLE PRECISION,
    mes INTEGER,
    CONSTRAINT fk_presupuesto_lineas_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE ingresos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    concepto VARCHAR(255) NOT NULL,
    monto DOUBLE PRECISION NOT NULL,
    mes INTEGER,
    CONSTRAINT fk_ingresos_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE costos_indirectos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
