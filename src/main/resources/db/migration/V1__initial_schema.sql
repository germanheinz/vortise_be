    mes INTEGER,
    CONSTRAINT fk_costos_indirectos_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE restricciones_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    restriccion VARCHAR(255),
    tipo VARCHAR(255),
    sector VARCHAR(255),
    nivel VARCHAR(255),
    unidad VARCHAR(255),
    rubro VARCHAR(255),
    responsable VARCHAR(255),
    fecha_solicitud DATE,
    fecha_maxima_entrega DATE,
    fecha_real_entrega DATE,
    carga VARCHAR(255),
