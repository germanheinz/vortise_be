CREATE TABLE restriccion_comentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restriccion_id BIGINT NOT NULL,
    autor VARCHAR(255),
    mensaje VARCHAR(255),
    creado_en TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_restriccion_comentarios_restriccion FOREIGN KEY (restriccion_id) REFERENCES restricciones_obra (id)
);

CREATE TABLE obra_tareas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    rubro_id BIGINT,
    nombre VARCHAR(255),
    sector VARCHAR(255),
    nivel VARCHAR(255),
    unidad VARCHAR(255),
    rubro VARCHAR(255),
    porcentaje_cumplimiento DOUBLE PRECISION,
    cumplimiento VARCHAR(255),
    causa_no_cumplimiento VARCHAR(255),
    comentario VARCHAR(255),
    horas_oficiales DOUBLE PRECISION,
    horas_ayudantes DOUBLE PRECISION,
    cantidad_prevista DOUBLE PRECISION,
    cantidad_real DOUBLE PRECISION,
    medida_correctiva VARCHAR(2000),
    descripcion VARCHAR(2000),
    fecha DATE,
    CONSTRAINT fk_obra_tareas_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT fk_obra_tareas_rubro FOREIGN KEY (rubro_id) REFERENCES rubros_obra (id)
);

CREATE TABLE entregas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    orden INTEGER,
    CONSTRAINT fk_entregas_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id)
);

CREATE TABLE tareas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrega_id BIGINT NOT NULL,
    fase VARCHAR(255),
    etapa VARCHAR(255),
    sistema VARCHAR(255),
    nombre VARCHAR(255) NOT NULL,
    status VARCHAR(255) DEFAULT 'PENDIENTE',
    avance_pct INTEGER,
    cantidad DOUBLE PRECISION,
    costo DOUBLE PRECISION,
    fecha_inicio DATE,
    fecha_fin DATE,
    mes INTEGER,
    CONSTRAINT fk_tareas_entrega FOREIGN KEY (entrega_id) REFERENCES entregas (id)
);

CREATE TABLE suscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titular VARCHAR(255) NOT NULL,
    usuario_id BIGINT,
    empresa_id BIGINT,
    plan_id BIGINT,
    stripe_customer_id VARCHAR(255) NOT NULL,
    stripe_subscription_id VARCHAR(255),
    estado VARCHAR(255),
    fin_prueba TIMESTAMP WITH TIME ZONE,
    fin_periodo_actual TIMESTAMP WITH TIME ZONE,
    cancela_al_final BOOLEAN NOT NULL DEFAULT FALSE,
    prueba_usada BOOLEAN NOT NULL DEFAULT FALSE,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_suscripciones_usuario UNIQUE (usuario_id),
    CONSTRAINT uq_suscripciones_empresa UNIQUE (empresa_id),
    CONSTRAINT uq_suscripciones_stripe_customer UNIQUE (stripe_customer_id),
    CONSTRAINT uq_suscripciones_stripe_subscription UNIQUE (stripe_subscription_id),
    CONSTRAINT fk_suscripciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios_empresa (id),
    CONSTRAINT fk_suscripciones_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_suscripciones_plan FOREIGN KEY (plan_id) REFERENCES planes_suscripcion (id)
);

CREATE TABLE pagos_suscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suscripcion_id BIGINT NOT NULL,
    stripe_invoice_id VARCHAR(255) NOT NULL,
    monto_centavos BIGINT NOT NULL,
    moneda VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_pagos_suscripcion_stripe_invoice UNIQUE (stripe_invoice_id),
    CONSTRAINT fk_pagos_suscripcion_suscripcion FOREIGN KEY (suscripcion_id) REFERENCES suscripciones (id)
);

CREATE TABLE stripe_eventos_procesados (
    event_id VARCHAR(255) PRIMARY KEY,
    tipo VARCHAR(255) NOT NULL,
    procesado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
