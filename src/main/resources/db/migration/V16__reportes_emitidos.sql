-- Reports issued from the obra reports screen and the images attached to them (hosted in Cloudinary).
CREATE TABLE reportes_emitidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    numero INTEGER NOT NULL,
    semana_desde DATE NOT NULL,
    semana_hasta DATE NOT NULL,
    fecha_corte DATE NOT NULL,
    emitido_por VARCHAR(255),
    emitido_por_usuario_id BIGINT,
    emitido_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    version_esquema INTEGER NOT NULL,
    snapshot TEXT NOT NULL,
    CONSTRAINT fk_reportes_emitidos_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT uq_reportes_emitidos_proyecto_numero UNIQUE (proyecto_id, numero)
);
CREATE INDEX ix_reportes_emitidos_proyecto ON reportes_emitidos (proyecto_id, numero);

-- reporte_id stays NULL while the image is a draft for the next report of the obra.
CREATE TABLE reporte_imagenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    reporte_id BIGINT,
    public_id VARCHAR(255) NOT NULL,
    url VARCHAR(1000) NOT NULL,
    ancho INTEGER,
    alto INTEGER,
    tamano_bytes BIGINT,
    leyenda VARCHAR(255),
    orden INTEGER NOT NULL,
    subido_por_usuario_id BIGINT,
    subido_en TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_reporte_imagenes_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT fk_reporte_imagenes_reporte FOREIGN KEY (reporte_id) REFERENCES reportes_emitidos (id),
    CONSTRAINT uq_reporte_imagenes_public_id UNIQUE (public_id)
);
CREATE INDEX ix_reporte_imagenes_proyecto ON reporte_imagenes (proyecto_id, reporte_id);
CREATE INDEX ix_reporte_imagenes_reporte ON reporte_imagenes (reporte_id);
