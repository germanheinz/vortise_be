-- Contratos de la obra (ESTRUCTURA-3-CAPAS-18): un contrato pertenece a un contratista (o a mano de obra propia) y puede cubrir varios rubros.
CREATE TABLE contratos_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    subcontratista_id BIGINT,
    CONSTRAINT fk_contratos_obra_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos (id),
    CONSTRAINT fk_contratos_obra_subcontratista FOREIGN KEY (subcontratista_id) REFERENCES catalogos_empresa (id)
);
CREATE INDEX ix_contratos_obra_proyecto ON contratos_obra (proyecto_id);

ALTER TABLE rubros_obra ADD COLUMN contrato_id BIGINT;
ALTER TABLE rubros_obra ADD CONSTRAINT fk_rubros_obra_contrato
    FOREIGN KEY (contrato_id) REFERENCES contratos_obra (id) ON DELETE SET NULL;

-- Los textos de contrato cargados con V19 pasan a contratos de la obra (sin contratista asociado) y los rubros los referencian.
INSERT INTO contratos_obra (proyecto_id, nombre)
    SELECT DISTINCT proyecto_id, contrato FROM rubros_obra WHERE contrato IS NOT NULL AND TRIM(contrato) <> '';
UPDATE rubros_obra
   SET contrato_id = (SELECT MIN(c.id) FROM contratos_obra c WHERE c.proyecto_id = rubros_obra.proyecto_id AND c.nombre = rubros_obra.contrato)
 WHERE contrato IS NOT NULL AND TRIM(contrato) <> '';
