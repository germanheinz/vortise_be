-- Refresh tokens rotativos (spec 015, S2). Aditiva: solo guarda el hash del token, nunca el valor.
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios_empresa(id) ON DELETE CASCADE,
    familia VARCHAR(36) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    inicio_familia TIMESTAMP WITH TIME ZONE NOT NULL,
    vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
    usado_en TIMESTAMP WITH TIME ZONE,
    revocado_en TIMESTAMP WITH TIME ZONE,
    session_version BIGINT NOT NULL
);
CREATE INDEX idx_refresh_tokens_familia ON refresh_tokens(familia);
CREATE INDEX idx_refresh_tokens_usuario ON refresh_tokens(usuario_id);
